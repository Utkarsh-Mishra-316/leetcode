class KthLargest {
private final PriorityQueue<Integer> minHeap;
    private final int k;

    public KthLargest(int k, int[] nums) {
        this.k = k;
        this.minHeap = new PriorityQueue<>(k);

        // Populate heap with initial numbers
        for (int num : nums) {
            add(num);
        }
    }
    
    public int add(int val) {
        if (minHeap.size() < k) {
            minHeap.offer(val);
        } else if (val > minHeap.peek()) {
            // New value is larger than the kth largest, replace the root
            minHeap.poll();
            minHeap.offer(val);
        }
        
        // Root is always the kth largest element
        return minHeap.peek();
        
    }
}

